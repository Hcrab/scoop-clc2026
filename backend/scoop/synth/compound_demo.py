"""Private seed-93 illustrative interventions; never exposed as AI evidence."""
from datetime import date, timedelta
import json

import numpy as np
import pandas as pd

from .strawberry_challenge import cells

START = date(2026, 7, 6)
FULL = date(2026, 7, 20)
END = date(2026, 8, 31)
STRAWBERRY_UPLIFT = .50
MANGO_KOWLOON_UPLIFT = .35
COATED_CHANGE = -.20
COATED_START = date(2026, 7, 20)
COATED_FULL = date(2026, 7, 27)
# Generate the original stochastic world first, then couple its existing draws
# to HEATWAVE. This baseline must not change with the public episode timing.
LEGACY_BASELINE_HEATWAVE = {date(2026, 7, 31): 33.6, **{
    date(2026, 8, day): temp for day, temp in
    [(1, 33.5), (2, 33.8), (3, 33.7), (4, 33.5), (5, 33.4),
     (6, 33.6), (7, 33.8), (8, 33.5)]}}
# All targets are within seven days of the Sunday forecast issued for Monday's
# order. Keep the episode's original mean (33.6 C) and range (33.4–33.8 C).
HEATWAVE = {date(2026, 7, 30): 33.6, date(2026, 7, 31): 33.4,
            date(2026, 8, 1): 33.8, date(2026, 8, 2): 33.6}


def shift_heat_episode(weather, forecasts, orders, days, *, dairy,
                       weather_total, weather_pref):
    """Shift the legacy episode in place without consuming any random draws.

    Call after seed93's demand interventions and before DC simulation. Inputs
    must be the legacy baseline generated by build_weather/build_demand; dairy
    follows the SKU axis of orders. Returns date -> temperature delta for audit.
    To compare an old world before loading data, temporarily replace this helper
    with a no-op and call generate(93), then restore it and call generate(93).
    Both runs retain identical RNG state on entry to DC simulation.
    """
    changes = {}
    response = weather_total + weather_pref * (.45 - np.asarray(dairy))
    for day in sorted(set(LEGACY_BASELINE_HEATWAVE) | set(HEATWAVE)):
        if day not in days:
            continue
        di = days.index(day)
        row = weather.index[di]
        old_temp = float(weather.at[row, 'tmax'])
        new_temp = (HEATWAVE[day] if day in HEATWAVE
                    else float(weather.attrs['background_tmax'][di]))
        delta = new_temp - old_temp
        weather.at[row, 'tmax'] = new_temp
        if delta == 0:
            continue
        changes[day] = delta
        orders[di] = np.floor(orders[di] * np.exp(response * delta) + .5)
        mask = forecasts.target_date == day
        lead = forecasts.loc[mask, 'issued_date'].map(lambda issued: (day - issued).days)
        weight = np.maximum(0., 1. - np.maximum(0, lead.to_numpy() - 7) / 9.)
        forecasts.loc[mask, 'tmax_fc'] = np.round(
            forecasts.loc[mask, 'tmax_fc'].to_numpy() + weight * delta, 1)
    return changes


def inject(orders, days, stores, products, product_tags):
    """Round the same baseline draws after multiplying only the named cells."""
    strawberry, _ = cells(products, product_tags)
    mango = np.flatnonzero(products.sku.isin(product_tags.loc[
        product_tags.tag_id == 'flavour:mango', 'sku']).to_numpy())
    coated = np.flatnonzero(products.sku.isin(product_tags.loc[
        product_tags.tag_id == 'feature:choc_coated', 'sku']).to_numpy())
    kowloon = np.flatnonzero(stores.district.to_numpy() == 'Kowloon')
    for di, day in enumerate(days):
        if START < day <= END:
            ramp = min(1., (day - START).days / (FULL - START).days)
            orders[di, :, strawberry] = np.floor(
                orders[di, :, strawberry] * (1 + STRAWBERRY_UPLIFT * ramp) + .5)
            grid = np.ix_(kowloon, mango)
            orders[di][grid] = np.floor(
                orders[di][grid] * (1 + MANGO_KOWLOON_UPLIFT * ramp) + .5)
            coated_ramp = min(1., max(0., (day - COATED_START).days / (COATED_FULL - COATED_START).days))
            orders[di, :, coated] = np.floor(
                orders[di, :, coated] * (1 + COATED_CHANGE * coated_ramp) + .5)
    districts = sorted(stores.district.unique())
    rows = []
    for identifier, kind, tag, areas, skus, effect, start, full in [
        ('N5A', 'intersection', None, districts, products.sku.iloc[strawberry].tolist(), STRAWBERRY_UPLIFT, START, FULL),
        ('N5B', 'intersection', 'flavour:mango', ['Kowloon'], products.sku.iloc[mango].tolist(), MANGO_KOWLOON_UPLIFT, START, FULL),
        ('N5C', 'trend', 'feature:choc_coated', districts, products.sku.iloc[coated].tolist(), COATED_CHANGE, COATED_START, COATED_FULL),
    ]:
        rows.append(dict(id=identifier, kind=kind, tag_id=tag, sku=None,
                         districts=areas, start_date=start, end_date=END,
                         expected_label='persistent', note=json.dumps(dict(
                             skus=skus, peak_fraction=effect, full_effect_date=full.isoformat(),
                             ramp=f'linear for {(full-start).days} days, then sustained',
                             rounding='baseline draws multiplied, halves up; no new RNG draws'))))
    rows.append(dict(id='N5D', kind='heatwave', tag_id=None, sku=None,
                     districts=districts, start_date=min(HEATWAVE), end_date=max(HEATWAVE),
                     expected_label='weather', note='Illustrative 30 July–2 August 33.4–33.8C heat spike; all targets fall within the issued forecast seven-day skill window.'))
    return pd.DataFrame(rows)
