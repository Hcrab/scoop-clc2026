import {test,expect} from '@playwright/test';
import {writeFile,mkdir} from 'node:fs/promises';
import path from 'node:path';

test('direction previews, Apply/Undo, action links and independent report columns',async({page,request})=>{
  test.setTimeout(300_000);page.setDefaultTimeout(45_000);
  const endpoint='/api/plans/P20260727',out=path.resolve('..','reports','screenshots');
  const evidence:any={mocked_responses:false,errors:[],screenshots:[],previews:[]};
  page.on('pageerror',error=>evidence.errors.push(error.message));
  const read=async(suffix='')=>{const response=await request.get(endpoint+suffix,{timeout:120_000});expect(response.ok(),await response.text()).toBeTruthy();return response.json()};
  const quantities=(detail:any)=>detail.orders.map((row:any)=>[row.sku,row.effective_cases]).sort((a:any,b:any)=>a[0].localeCompare(b[0]));
  const initial=await read(),card=initial.cohort_cards[0];
  expect(initial.plan.service_level).toBeNull();expect(initial.review.status).toBe('complete');
  const original=quantities(initial);
  let changed=false;
  try{
    await request.put(endpoint+'/flow',{data:{step:'report'}});
    await page.goto('/');
    const side=page.locator('.cohort-panel'),left=page.locator('.report-column');
    const slider=side.getByRole('slider',{name:'In-stock target'});
    await expect(side.getByRole('heading',{name:"This week's direction",exact:true})).toBeVisible();
    await expect(side).toContainText('Save space');await expect(side).toContainText('Avoid stockouts');
    await expect(side).toContainText('cases this week');await expect(side).toContainText('· auto');
    await expect(side.locator('.cohort-card').first()).toContainText(`Demand +${Math.round(card.effect_pct)}% above forecast`);
    await expect(side.locator('.cohort-card').first()).toContainText(`${card.case_change} cases added to this week's order`);
    await expect(side.locator('.cohort-card').first()).toContainText('Cold-store peak');
    const previewResponse=(level:number|null)=>page.waitForResponse(response=>response.url().endsWith('/direction-preview')&&response.request().method()==='POST'&&response.request().postDataJSON().service_level===level);
    const lowResponse=previewResponse(.5);await slider.focus();await slider.press('Home');
    const low=await(await lowResponse).json();evidence.previews.push(low);
    await expect(side).toContainText(`${low.cases.toLocaleString('en-HK')} cases this week`);
    expect(quantities(await read())).toEqual(original);
    const autoResponse=previewResponse(null);await side.getByText('Reset to auto',{exact:true}).click();
    const auto=await(await autoResponse).json();evidence.previews.push(auto);
    await expect(side).toContainText('· auto');expect(quantities(await read())).toEqual(original);
    const highResponse=previewResponse(.98);await slider.focus();await slider.press('End');
    const high=await(await highResponse).json();evidence.previews.push(high);
    expect(high.cases).toBeGreaterThan(low.cases);
    await expect(side).toContainText(`${high.cases.toLocaleString('en-HK')} cases this week`);
    expect(quantities(await read())).toEqual(original);
    const applied=page.waitForResponse(response=>response.url().endsWith('/goal')&&response.request().method()==='PUT');
    await side.getByRole('button',{name:'Apply',exact:true}).click();
    expect((await applied).ok()).toBeTruthy();changed=true;
    await expect(side.locator('.edit-receipt')).toBeVisible();
    await expect(side.locator('.edit-receipt').getByRole('button',{name:'Undo',exact:true})).toBeVisible();
    const after=await read(),projection=(await read('/order-summary')).capacity;
    expect(after.plan.service_level).toBe(.98);
    expect(after.orders.reduce((sum:number,row:any)=>sum+row.effective_cases,0)).toBe(high.cases);
    expect(projection.projected_peak_pallets).toBeCloseTo(high.projected_peak_pallets,6);
    const undo=page.waitForResponse(response=>/\/edits\/\d+\/undo$/.test(response.url())&&response.request().method()==='POST');
    await side.locator('.edit-receipt').getByRole('button',{name:'Undo',exact:true}).click();
    expect((await undo).ok()).toBeTruthy();changed=false;
    await expect.poll(async()=>JSON.stringify(quantities(await read()))).toBe(JSON.stringify(original));
    expect((await read()).plan.service_level).toBeNull();
    await expect(side).toContainText('· auto');
    await expect(side.locator('.cohort-preview-row')).not.toContainText('updating…');
    await expect(side).toContainText(`${auto.cases.toLocaleString('en-HK')} cases this week`);
    await expect(page.locator('.inline-refresh')).toHaveCount(0);
    await expect(page.frameLocator('.generated-report iframe').locator('figure[data-chart] svg').first()).toBeVisible();
    await mkdir(out,{recursive:true});
    const shot=async(name:string)=>{await page.screenshot({path:path.join(out,name),animations:'disabled'});evidence.screenshots.push(`reports/screenshots/${name}`)};
    await left.evaluate(el=>el.scrollTop=0);await side.evaluate(el=>el.scrollTop=0);
    await shot('m3-direction.png');
    const topBefore=await side.boundingBox(),headerBefore=await page.locator('.stage-tabs').boundingBox();
    await left.evaluate(el=>el.scrollTop=Math.min(700,el.scrollHeight-el.clientHeight));
    expect(await left.evaluate(el=>el.scrollTop)).toBeGreaterThan(100);
    expect(await side.evaluate(el=>el.scrollTop)).toBe(0);
    expect((await side.boundingBox())!.y).toBeCloseTo(topBefore!.y,1);
    expect((await page.locator('.stage-tabs').boundingBox())!.y).toBeCloseTo(headerBefore!.y,1);
    await shot('m3-scrolled-left.png');
    const action=page.frameLocator('.generated-report iframe').locator('.native-cohort-action').first();
    await expect(action).toContainText(card.name);await expect(action).toContainText(card.magnitude);
    expect(await action.textContent()).not.toMatch(/cases|pallets|HK\$/i);
    const box=await action.boundingBox(),leftBox=await left.boundingBox();
    await left.evaluate((el,amount)=>{el.scrollTop+=amount},box!.y-leftBox!.y-100);
    await action.click();
    await expect(side.locator(`.cohort-card[data-cohort-id="${card.id}"]`)).toHaveClass(/is-highlighted/);
    await shot('m3-actions.png');
    evidence.independent_scroll={left_scroll_top:await left.evaluate(el=>el.scrollTop),right_scroll_top:await side.evaluate(el=>el.scrollTop),header_y:headerBefore!.y};
    await page.setViewportSize({width:900,height:900});
    await side.getByRole('heading',{name:"This week's direction",exact:true}).scrollIntoViewIfNeeded();
    expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBeTruthy();
    await shot('m3-narrow-direction.png');
    evidence.preview_matches_apply=true;evidence.undo_restores_exact_orders=true;evidence.focused_card=card.id;
    expect(evidence.errors).toEqual([]);
  }finally{
    if(changed){const current=await read(),edit=[...current.decisions].reverse().find((item:any)=>item.key==='goal_edit'&&!item.value.undone_at);if(edit)await request.post(`${endpoint}/edits/${edit.id}/undo`)}
    const settings=await(await request.get('/api/demo-settings')).json();
    const reset=await request.post('/api/demo-settings/reset',{data:{scenario_id:settings.scenario_id,week_start:'2026-07-27'}});expect(reset.ok()).toBeTruthy();
    expect(quantities(await read())).toEqual(original);
    await writeFile(path.resolve('..','reports','m3-browser.json'),JSON.stringify(evidence,null,2)+'\n');
  }
});
