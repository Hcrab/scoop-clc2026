import { test, expect } from '@playwright/test';
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

test('real report, context, grouped orders, shared dashboard and Play', async ({ page, request }) => {
  test.setTimeout(900_000);
  page.setDefaultTimeout(60_000);
  const endpoint = '/api/plans/P20260727';
  const out = path.resolve('..', 'reports', 'screenshots');
  await mkdir(out, { recursive: true });
  const read = async (suffix = '') => {
    const response = await request.get(endpoint + suffix, { timeout: 90_000 });
    expect(response.ok(), await response.text()).toBeTruthy();
    return response.json();
  };
  const screenshot = async (name: string) => {
    await page.screenshot({ path: path.join(out, `p4-${name}.png`), fullPage: false });
  };
  const records: Record<string, unknown> = { mocked_responses: false, plan: 'P20260727' };
  const initial=await read();
  expect(initial.review.model).toContain('gemini-3.8-flash');
  expect(initial.review.presentation.html).not.toMatch(/<svg\b/i);
  records.report_model=initial.review.model;
  const initialCohorts=await read('/cohorts');
  const definition=initialCohorts.cards[0];
  const signature=(terms:any[])=>JSON.stringify(terms.map(t=>[t.id,t.included]).sort((a,b)=>a[0].localeCompare(b[0])));
  const existing=initialCohorts.overrides.find((o:any)=>o.type==='ends_on'&&signature(o.tag_path||[])===signature(definition.tag_path)&&JSON.stringify([...(o.districts||[])].sort())===JSON.stringify([...definition.districts].sort()));
  const endsOn=existing?.value==='2026-08-10'?'2026-08-03':'2026-08-10';
  await page.goto('/');
  await page.getByRole('tab', { name: /Report & direction/ }).click();
  const panel = page.getByRole('complementary', { name: 'Demand changes and context' });
  const card = panel.locator('.cohort-card').first();
  await expect(card).toBeVisible();
  await expect(page.locator('.generated-report iframe')).toBeVisible();
  await expect(page.frameLocator('.generated-report iframe').locator('figure[data-chart="line"] svg').first()).toBeVisible();
  await screenshot('report');
  await card.getByRole('button', { name: /^Expand .* trend$/ }).click();
  await expect(card.locator('.cohort-chart svg')).toBeVisible();
  await card.getByText('Evidence and products', { exact: true }).click();
  await expect(card.locator('.cohort-table-wrap tbody tr').first()).toBeVisible();
  await screenshot('card');

  await card.getByText('Add context', { exact: true }).click();
  await card.locator('.cohort-context select').first().selectOption('ends_on');
  await card.getByLabel('Ends before', { exact: true }).fill(endsOn);
  const contextResponse = page.waitForResponse(r => r.url().endsWith('/overrides') && r.request().method() === 'POST');
  await card.getByRole('button', { name: 'Apply context', exact: true }).click();
  const context = await contextResponse;
  expect(context.ok(), await context.text()).toBeTruthy();
  const contextEdit = await context.json();
  expect(contextEdit.affected_orders.some((o: any) => o.before !== o.after)).toBeTruthy();
  await expect(panel.locator('.edit-receipt')).toContainText('Plan updated:');
  await screenshot('override');
  records.context_edit = {id:contextEdit.edit_id,ends_on:endsOn};
  const afterContext = await read();
  expect(afterContext.plan.stage).toBe('direction');
  await page.getByRole('tab', { name: /Orders/ }).click();
  const groups = await read('/order-summary');
  const cohorts = await read('/cohorts');
  expect(groups.groups[0].id).toBe(cohorts.cards[0].id);
  const groupedSkus = groups.groups.flatMap((g: any) => g.skus);
  expect(new Set(groupedSkus).size).toBe(afterContext.orders.length);
  expect(groupedSkus.length).toBe(afterContext.orders.length);
  const firstGroup = page.locator('.action-group').first();
  await expect(firstGroup.locator('tbody tr')).toHaveCount(Math.min(20, groups.groups[0].skus.length));
  if (groups.groups[0].skus.length > 20) {
    await firstGroup.getByRole('button', { name: 'Next', exact: true }).click();
    await expect(firstGroup.locator('tbody tr')).toHaveCount(Math.min(20, groups.groups[0].skus.length - 20));
    await firstGroup.getByRole('button', { name: 'Previous', exact: true }).click();
  }
  expect(await page.locator('.action-capacity').evaluate(e => getComputedStyle(e).position)).toBe('sticky');
  const row = firstGroup.locator('tbody tr').first();
  const input = row.getByRole('spinbutton');
  const oldCases = Number(await input.inputValue());
  const bootstrap=await (await request.get('/api/bootstrap')).json();
  const firstSku=await row.locator('small').first().textContent();
  const product=bootstrap.products.find((p:any)=>firstSku?.startsWith(p.sku));
  expect(product).toBeTruthy();
  const addedCases=Math.ceil(2*groups.capacity.capacity_pallets*product.cases_per_pallet);
  const editResponse = page.waitForResponse(r => r.url().endsWith('/orders/bulk') && r.request().method() === 'POST');
  await input.fill(String(oldCases+addedCases));
  await input.press('Enter');
  const edited = await editResponse;
  expect(edited.ok(), await edited.text()).toBeTruthy();
  const inlineEdit = await edited.json();
  await expect(page.locator('.action-list .edit-receipt')).toContainText('Plan updated:');
  const changedSummary = await read('/order-summary');
  expect(changedSummary.edited_skus).toContain(inlineEdit.affected_orders[0].sku);
  expect(changedSummary.capacity.projected_peak_pallets).toBeGreaterThan(groups.capacity.projected_peak_pallets);
  await expect(page.getByRole('button',{name:'Approve orders',exact:true})).toBeDisabled();
  const shownPeak = new Intl.NumberFormat('en-US', { maximumFractionDigits: 1 }).format(changedSummary.capacity.projected_peak_pallets);
  await expect(page.locator('.action-capacity')).toContainText(shownPeak);
  await screenshot('orders-edit');
  const undoResponse = page.waitForResponse(r => r.url().endsWith(`/edits/${inlineEdit.edit_id}/undo`) && r.request().method() === 'POST');
  await page.locator('.action-list .edit-receipt').getByRole('button', { name: 'Undo', exact: true }).click();
  expect((await undoResponse).ok()).toBeTruthy();
  expect((await read()).orders).toEqual(afterContext.orders);
  const approveResponse = page.waitForResponse(r => r.url().endsWith('/approve-orders') && r.request().method() === 'POST');
  await page.getByRole('button', { name: 'Approve orders', exact: true }).click();
  const approval = await approveResponse;
  expect(approval.ok(), await approval.text()).toBeTruthy();
  await expect(page.getByRole('tab', { name: /Watch & play/ })).toHaveAttribute('aria-selected', 'true');
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
  await expect(page.locator('.dashboard-widget').first()).toBeVisible();
  records.order_groups = groups.groups.map((g: any) => ({ id: g.id, count: g.skus.length }));
  records.inline_edit = { edit_id: inlineEdit.edit_id, exact_undo: true, before_cases:oldCases,after_cases:oldCases+addedCases,before_peak_pallets:groups.capacity.projected_peak_pallets,peak_pallets: changedSummary.capacity.projected_peak_pallets };

  const stamp = Date.now().toString(36);
  const title = `Warehouse pallets ${stamp}`;
  await page.getByRole('button', { name: 'Add widget', exact: true }).click();
  const sheet = page.getByRole('dialog', { name: 'Add widget', exact: true });
  await sheet.getByLabel(/^Measure/).selectOption('pallets');
  await sheet.getByLabel('Title', { exact: true }).fill(title);
  await expect(sheet.locator('.dashboard-preview strong')).toBeVisible();
  await expect(sheet.locator('.dashboard-preview strong')).toContainText('pallets');
  const addedResponse = page.waitForResponse(r => r.url().endsWith('/dashboard') && r.request().method() === 'POST');
  await sheet.getByRole('button', { name: 'Add widget', exact: true }).click();
  expect((await addedResponse).ok()).toBeTruthy();
  await expect(page.locator('.dashboard-widget').filter({ has: page.getByRole('heading', { name: title, exact: true }) })).toBeVisible();
  const beforeDrag = await read('/dashboard');
  const dragged = page.locator('.dashboard-widget').filter({ has: page.getByRole('heading', { name: title, exact: true }) });
  const target = page.locator('.dashboard-widget').first();
  await expect(dragged).toHaveAttribute('draggable', 'true');
  const reorderedResponse = page.waitForResponse(r => r.url().endsWith('/dashboard-layout') && r.request().method() === 'PUT');
  await dragged.locator('header').dragTo(target.locator('header'));
  expect((await reorderedResponse).ok()).toBeTruthy();
  const reordered = await read('/dashboard');
  expect(reordered.widgets[0].id).toBe(beforeDrag.widgets.at(-1).id);
  await page.reload();
  await page.getByRole('button', { name: 'Dashboard', exact: true }).click();
  await expect(page.locator('.dashboard-widget').first().getByRole('heading')).toHaveText(title);
  const removeResponse = page.waitForResponse(r => r.url().includes('/dashboard/') && r.request().method() === 'DELETE');
  await page.locator('.dashboard-widget').first().getByRole('button', { name: 'Remove', exact: true }).click();
  const removal = await removeResponse;
  expect(removal.ok(), await removal.text()).toBeTruthy();
  const removeEdit = await removal.json();
  await expect(page.locator('.dashboard-widget').filter({ hasText: title })).toHaveCount(0);
  const removeUndo = page.waitForResponse(r => r.url().endsWith(`/edits/${removeEdit.edit_id}/undo`) && r.request().method() === 'POST');
  await page.locator(`.dashboard .edit-receipt[data-edit-id="${removeEdit.edit_id}"]`).getByRole('button', { name: 'Undo', exact: true }).click();
  expect((await removeUndo).ok()).toBeTruthy();
  expect((await read('/dashboard')).widgets.map((w: any) => w.id)).toEqual(reordered.widgets.map((w: any) => w.id));
  await screenshot('dashboard');
  records.dashboard = { layout_persisted_after_reload: true, remove_exact_undo: true };

  const chatTitle = `Warehouse stock ${stamp}`;
  await page.getByRole('button', { name: /Show discussion/ }).click();
  await page.getByRole('textbox', { name: 'Discuss this plan' }).fill(`Add a warehouse on-hand widget titled "${chatTitle}".`);
  const chatResponse = page.waitForResponse(r => r.url().endsWith('/chat/stream') && r.request().method() === 'POST', { timeout: 180_000 });
  await page.getByRole('button', { name: 'Send message', exact: true }).click();
  const chat = await chatResponse;
  expect(chat.ok(), await chat.text()).toBeTruthy();
  const stream = await chat.text();
  const event = stream.split('\n\n').find(part => part.startsWith('event: result\n'));
  expect(event, stream.slice(-2000)).toBeTruthy();
  const reply = JSON.parse(event!.slice(event!.indexOf('data: ') + 6));
  expect(reply.provider, reply.fallback_reason).toBe('gemini');
  expect(reply.fallback_reason).toBeUndefined();
  expect(reply.tool_trace.some((t: any) => t.name === 'add_widget' && t.status === 'ok')).toBeTruthy();
  await expect(page.locator('.dashboard-widget').filter({ has: page.getByRole('heading', { name: chatTitle, exact: true }) })).toBeVisible();
  await screenshot('chat-widget');
  records.chat_widget = { title: chatTitle, provider: reply.provider, tool_trace: reply.tool_trace };

  await page.getByRole('button', { name: 'Play', exact: true }).click();
  const widgetsBeforePlay = (await read('/dashboard')).widgets.map((w: any) => w.id);
  await expect(page.locator('.play .dashboard-widget')).toHaveCount(widgetsBeforePlay.length);
  await page.getByRole('button', { name: '4×', exact: true }).click();
  const playResponse = page.waitForResponse(r => r.url().endsWith('/play') && r.request().method() === 'POST', { timeout: 180_000 });
  await page.getByRole('button', { name: 'Play this order through', exact: true }).click();
  const simulationResponse = await playResponse;
  expect(simulationResponse.ok(), await simulationResponse.text()).toBeTruthy();
  const simulation = await simulationResponse.json();
  await expect(page.locator('.play-autopilot')).toHaveText('Week-2 orders are placed automatically on both sides.');
  await expect(page.getByRole('tab', { name: /Orders/ })).toBeDisabled();
  await expect(page.getByRole('textbox', { name: 'Discuss this plan' })).toBeDisabled();
  await screenshot('play');
  await expect(page.locator('.play-outcomes')).toBeVisible({ timeout: 90_000 });
  await expect(page.locator('.play-outcomes strong')).toHaveCount(3);
  const number = (value: number, digits = 0) => new Intl.NumberFormat('en-US', { maximumFractionDigits: digits }).format(value);
  const outcomes = page.locator('.play-outcomes strong');
  await expect(outcomes.nth(0)).toHaveText(number(Math.abs(simulation.affected_comparison.units_saved)));
  await expect(outcomes.nth(1)).toHaveText(number(simulation.affected_comparison.pallet_difference, 1));
  await expect(outcomes.nth(2)).toHaveText(number(Math.abs(simulation.affected_comparison.stockout_days_avoided)));
  expect(simulation.days).toBeGreaterThan(7);
  expect(simulation.days).toBeLessThanOrEqual(21);
  expect(simulation.affected_skus.length).toBeGreaterThan(0);
  await expect(page.locator('.play .dashboard-widget')).toHaveCount(widgetsBeforePlay.length);
  const stockChart = page.locator('.play .dashboard-widget').filter({ has: page.getByRole('heading', { name: chatTitle, exact: true }) });
  await expect(stockChart).toContainText('Moving-average rule');
  const ruleStockoutDays=simulation.runs.baseline.per_sku.lost.filter((row:number[])=>row.some(value=>value>0)).length;
  await expect(stockChart.locator('g[data-series="dot"] circle')).toHaveCount(ruleStockoutDays);
  await expect(stockChart.locator('g[data-series="rule"] polyline')).toHaveCount(1);
  await page.getByText('See full comparison', { exact: true }).click();
  await expect(page.locator('.play-comparison table')).toBeVisible();
  await screenshot('result');
  records.play = { days: simulation.days, affected_skus: simulation.affected_skus, summary: simulation.summary, affected_comparison: simulation.affected_comparison, same_widgets: widgetsBeforePlay, rule_stockout_dots:ruleStockoutDays, events: simulation.events };
  await writeFile(path.resolve('..', 'reports', 'p4-browser-acceptance.json'), JSON.stringify(records, null, 2));
});
